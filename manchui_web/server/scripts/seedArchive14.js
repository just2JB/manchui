const toNotice = ([date, title, kind, , memo, endDate]) => ({
  title,
  date: date || "",
  kind: kind === "공지" ? "공지" : "일정",
  endDate: endDate || "",
  body: memo || "",
});

async function main() {
  const total = EVENTS.reduce((n, e) => n + e.items.length, 0);
  console.log(`행사 ${EVENTS.length}개 · 타임라인 항목 ${total}개\n`);

  if (!confirmed) {
    for (const e of EVENTS) {
      console.log(`[${e.generation}기] ${e.title}  (${e.startDate}${e.endDate ? ` ~ ${e.endDate}` : ""}) · 항목 ${e.items.length}`);
    }
    console.log("\n확인만 했습니다. 실제로 넣으려면: node scripts/seedArchive14.js --yes");
    return;
  }

  if (!process.env.MONGO_URI) throw new Error("MONGO_URI 가 설정되지 않았습니다 (.env 확인).");
  await mongoose.connect(process.env.MONGO_URI);

  let created = 0;
  for (const e of EVENTS) {
    const exists = await ArchiveEvent.exists({ title: e.title, generation: e.generation });
    if (exists) {
      console.log(`- 건너뜀 (이미 있음): [${e.generation}기] ${e.title}`);
      continue;
    }
    await ArchiveEvent.create({
      title: e.title,
      startDate: e.startDate,
      endDate: e.endDate || e.startDate,
      generation: e.generation,
      category: e.category || "기타",
      tags: e.tags,
      summary: e.summary,
      notices: e.items.map(toNotice),
    });
    created += 1;
    console.log(`+ [${e.generation}기] ${e.title} · 항목 ${e.items.length}`);
  }
  console.log(`\n완료: 행사 ${created}개 추가`);
}

main()
  .catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  })
  .finally(() => mongoose.disconnect());
